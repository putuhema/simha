/**
 * Makes a printable patient document from Khanza data: riwayat pasien (all
 * visits), CPPT / SOAP of a visit, or the resume medis of a visit (the one
 * written in Khanza, or a draft from the CPPT when there is none).
 *
 * The server fills a fixed HTML template; the AI only asks for the document
 * and may summarise the returned data in its answer. The model sees the data
 * but free clinical text is masked for external providers (privacy/mask.ts).
 */
import { DocumentInfo, DocumentKind } from "@simrs/shared";
import { Effect, Schema } from "effect";
import { ToolError } from "../errors.ts";
import { CurrentActor, CurrentSession, CurrentToolCall } from "../khanza/current-tool-call.ts";
import { ResultStore } from "../info/ResultStore.ts";
import { NoRawat, NoRkmMedis } from "../read/common.ts";
import { defineTool } from "../tool.ts";
import { cpptOf, detailsOf, hospital, identityOf, labOf, radiologyOf, resumeOf, visitOf, visitsOf } from "./data.ts";
import { cpptHtml, resumeHtml, riwayatHtml } from "./html.ts";

const NAME = "dokumenPasien";

const plural = (n: number, word: string) => `${n} ${word}`;

export const dokumenPasien = defineTool({
  name: NAME,
  kind: "render",
  description:
    "Make a printable patient document from Khanza data and show it to the user (with Print / PDF / download). " +
    "jenis: 'riwayat' = history of all visits of a patient (needs noRkmMedis); 'cppt' = CPPT / SOAP notes of one " +
    "visit with diagnoses, lab and radiology (needs noRawat); 'resume' = resume medis of one visit, or a draft " +
    "built from the CPPT when no resume exists (needs noRawat). The document is generated by the server, not by " +
    "you: do not rewrite it in your answer. Give at most a short summary, and say that it is a summary.",
  parameters: Schema.Struct({
    jenis: DocumentKind,
    noRkmMedis: Schema.optionalKey(NoRkmMedis),
    noRawat: Schema.optionalKey(NoRawat),
  }),
  output: Schema.Struct({ document: DocumentInfo, data: Schema.Unknown }),
  handler: Effect.fn(NAME)(function* (params) {
    const store = yield* ResultStore;
    const meta = { hospital: yield* hospital, generatedAt: new Date(), generatedBy: yield* CurrentActor };

    let html: string;
    let judul: string;
    let subjek: string;
    let ringkas: string;
    let data: unknown;

    if (params.jenis === "riwayat") {
      const rm = params.noRkmMedis?.trim();
      if (!rm) return yield* new ToolError({ tool: NAME, message: "Riwayat pasien butuh noRkmMedis." });
      const identity = yield* identityOf(NAME, rm);
      const { visits, more } = yield* visitsOf(rm);
      const details = yield* detailsOf(visits);
      html = riwayatHtml({ identity, visits: details, more }, meta);
      judul = "Riwayat pasien";
      subjek = `RM ${identity.noRkmMedis} · ${identity.nama ?? ""}`;
      ringkas = `${plural(details.length, "kunjungan")}${more ? " terakhir" : ""}, ${plural(
        details.reduce((n, v) => n + v.diagnosis.length, 0),
        "diagnosis",
      )}`;
      data = { identitas: identity, kunjungan: details, adaKunjunganLebihLama: more };
    } else {
      const noRawat = params.noRawat?.trim();
      if (!noRawat) return yield* new ToolError({ tool: NAME, message: `Dokumen ${params.jenis} butuh noRawat.` });
      const { visit, noRkmMedis } = yield* visitOf(NAME, noRawat);
      const identity = yield* identityOf(NAME, noRkmMedis);
      const [details] = yield* detailsOf([visit]);
      const entries = yield* cpptOf(noRawat);
      const lab = yield* labOf(noRawat);
      const visitDetails = details ?? { ...visit, diagnosis: [], tindakan: [], obat: [], kamar: [] };
      subjek = `RM ${identity.noRkmMedis} · ${identity.nama ?? ""} · ${noRawat}`;
      if (params.jenis === "cppt") {
        const radiology = yield* radiologyOf(noRawat);
        html = cpptHtml({ identity, visit, diagnosis: visitDetails.diagnosis, entries, lab, radiology }, meta);
        judul = "CPPT / SOAP";
        ringkas = [
          plural(entries.length, "catatan CPPT"),
          plural(visitDetails.diagnosis.length, "diagnosis"),
          lab.length ? plural(lab.length, "hasil lab") : null,
          radiology.length ? plural(radiology.length, "hasil radiologi") : null,
        ]
          .filter(Boolean)
          .join(", ");
        data = { identitas: identity, kunjungan: visit, diagnosis: visitDetails.diagnosis, cppt: entries, lab, radiologi: radiology };
      } else {
        const resume = yield* resumeOf(noRawat, visit.jenis === "Rawat inap");
        html = resumeHtml({ identity, visit: visitDetails, resume, firstEntry: entries[0], lab }, meta);
        judul = resume ? "Resume medis" : "Draf resume medis";
        ringkas = resume ? `dari Khanza${resume.dokter ? `, ${resume.dokter}` : ""}` : "belum ada resume di Khanza; draf dari CPPT";
        data = { identitas: identity, kunjungan: visitDetails, resume, sumber: resume ? "khanza" : "draf dari CPPT" };
      }
    }

    const document: DocumentInfo = {
      id: crypto.randomUUID(),
      jenis: params.jenis,
      judul,
      subjek,
      ringkas,
      dibuatOleh: meta.generatedBy,
      dibuatPada: meta.generatedAt.toISOString(),
    };
    yield* store.saveDocument(document, html, { toolCallId: yield* CurrentToolCall, sessionId: yield* CurrentSession });
    return { document, data };
  }),
  forModel: ({ document, data }) => ({
    ditampilkan: true,
    dokumen: document,
    data,
    catatan:
      "Dokumen sudah tampil di layar pengguna (bisa dicetak). Jangan menyalin isinya. Jika diminta, beri ringkasan " +
      "singkat dan sebut bahwa itu ringkasan AI yang perlu diperiksa. Teks catatan klinis bisa disamarkan untuk AI.",
  }),
});
